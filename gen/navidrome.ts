/**
 * Navidrome target.
 *
 * Navidrome themes are Material-UI objects compiled into the UI bundle, so this
 * emits the source file the build injects. Both variants are exported because
 * the build patches `useCurrentTheme` so the UI's "Auto" preference resolves to
 * these instead of Navidrome's built-in Light/Dark.
 */

import { mutedTokens } from "./derive.ts";
import type { Palette } from "./palette.ts";

const BANNER = "// Generated by `deno task gen` from spec/palette.json — do not edit.";

export function renderNavidrome(palette: Palette): string {
  const { light, dark } = palette;
  const lightMuted = mutedTokens("light", palette)[2];
  const darkMuted = mutedTokens("dark", palette)[2];

  return [
    BANNER,
    "// Navidrome has no external theme loading; these are injected at build time.",
    "",
    "export const MotifLight = {",
    '  themeName: "Motif Light",',
    "  palette: {",
    `    primary: { main: "${light.primary}" },`,
    `    secondary: { main: "${light.secondary}" },`,
    `    background: { default: "${light.bg}", paper: "${light.surface}" },`,
    `    text: { primary: "${light.text}", secondary: "${lightMuted}" },`,
    '    type: "light",',
    "  },",
    '  player: { theme: "light" },',
    "};",
    "",
    "export const MotifDark = {",
    '  themeName: "Motif Dark",',
    "  palette: {",
    `    primary: { main: "${dark.primary}" },`,
    `    secondary: { main: "${dark.secondary}" },`,
    `    background: { default: "${dark.bg}", paper: "${dark.surface}" },`,
    `    text: { primary: "${dark.text}", secondary: "${darkMuted}" },`,
    '    type: "dark",',
    "  },",
    '  player: { theme: "dark" },',
    "};",
    "",
  ].join("\n");
}
