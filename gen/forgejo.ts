/**
 * Forgejo target.
 *
 * Emits the override fragment appended to Forgejo's stock theme. Everything not
 * named here is inherited, so the theme keeps tracking Forgejo upgrades while
 * the ~230 `--color-*` variables are only overridden where Motif differs.
 */

import { alphaCss, mixCss, round } from "./color.ts";
import { assertAccessible, type MutedTokens, mutedTokens } from "./derive.ts";
import type { Palette, PaletteMode, Scheme } from "./palette.ts";

const BANNER = "/* Generated by `deno task gen` from spec/palette.json — do not edit. */";

/** Neutral ramp for the light theme: surface → text. */
const ZINC_RAMP = [
  ["50", 0.03],
  ["100", 0.06],
  ["150", 0.09],
  ["200", 0.12],
  ["250", 0.15],
  ["300", 0.21],
  ["350", 0.32],
  ["400", 0.42],
  ["450", 0.5],
  ["500", 0.57],
  ["550", 0.64],
  ["600", 0.7],
  ["650", 0.75],
  ["700", 0.8],
  ["750", 0.85],
  ["800", 0.9],
  ["850", 0.94],
  ["900", 0.98],
] as const satisfies ReadonlyArray<readonly [string, number]>;

/** Dark-theme neutrals darker than the background. */
const STEEL_DARKER = [
  ["900", 0.3],
  ["850", 0.15],
] as const satisfies ReadonlyArray<readonly [string, number]>;

/** Dark-theme neutrals lighter than the background: background → text. */
const STEEL_RAMP = [
  ["750", 0.08],
  ["700", 0.14],
  ["650", 0.2],
  ["600", 0.27],
  ["550", 0.35],
  ["500", 0.43],
  ["450", 0.5],
  ["400", 0.57],
  ["350", 0.64],
  ["300", 0.71],
  ["250", 0.78],
  ["200", 0.84],
  ["150", 0.9],
  ["100", 0.96],
] as const satisfies ReadonlyArray<readonly [string, number]>;

export function renderForgejo(scheme: Scheme, palette: Palette): string {
  const mode = palette[scheme];
  const muted = mutedTokens(scheme, palette);
  const worst = assertAccessible(scheme, palette);
  const out: string[] = [BANNER, ":root{"];

  if (scheme === "light") {
    out.push(`--color-body:${mode.bg};`);
    out.push(mutedComment(scheme, worst));
    pushMuted(out, muted);
    out.push(`--color-secondary:${mode.border};`);
    out.push(`--color-input-border:${mode.border};`);
    out.push(`--color-input-border-hover:${mode.borderHover};`);
    out.push(`--color-timeline:${mode.border};`);
    out.push(`--color-hover:${alphaCss(mode.surface, 0.8)};`);
    out.push(`--color-active:${mode.border};`);
    out.push(`--color-selection-bg:${mode.primary};`);
    pushZinc(out, mode);
  } else {
    out.push(`--color-secondary:${mode.border};`);
    out.push(mutedComment(scheme, worst));
    pushMuted(out, muted);
    out.push(`--color-input-border:${mode.border};`);
    out.push(`--color-input-border-hover:${mode.borderHover};`);
    out.push(`--color-timeline:${mode.border};`);
    out.push(`--color-selection-bg:${mode.primary};`);
    out.push(`--color-selection-fg:${mode.bg};`);
    pushSteel(out, mode);
  }

  out.push(...primaryScale(scheme, mode));
  out.push("}");
  return `${out.join("\n")}\n`;
}

function mutedComment(scheme: Scheme, worst: number): string {
  const base = scheme === "light" ? "surface" : "background";
  return [
    "/* Muted text: WCAG 2.2 SC 1.4.3 (AA, >= 4.5:1 for normal text). Derived by",
    `   mixing ${base} toward text; the lightest step still clears AA on every`,
    `   text-bearing surface (worst case ${round(worst)}:1). --color-placeholder-text`,
    "   follows --color-text-light-3. Enforced by gen/derive.ts. */",
  ].join("\n");
}

function pushMuted(out: string[], muted: MutedTokens): void {
  out.push(`--color-text-light:${muted[0]};`);
  out.push(`--color-text-light-1:${muted[1]};`);
  out.push(`--color-text-light-2:${muted[2]};`);
  out.push(`--color-text-light-3:${muted[3]};`);
}

function pushZinc(out: string[], mode: PaletteMode): void {
  for (const [step, ratio] of ZINC_RAMP) {
    out.push(`--zinc-${step}:${mixCss(mode.surface, mode.text, ratio)};`);
  }
}

function pushSteel(out: string[], mode: PaletteMode): void {
  for (const [step, ratio] of STEEL_DARKER) {
    out.push(`--steel-${step}:${mixCss(mode.bg, "black", ratio)};`);
  }
  out.push(`--steel-800:${mode.bg};`);
  for (const [step, ratio] of STEEL_RAMP) {
    out.push(`--steel-${step}:${mixCss(mode.bg, mode.text, ratio)};`);
  }
}

function primaryScale(scheme: Scheme, mode: PaletteMode): string[] {
  const primary = mode.primary;
  const out: string[] = [`--color-primary:${primary};`];

  if (scheme === "light") {
    out.push("--color-primary-contrast:#ffffff;");
    out.push(`--color-primary-dark-1:${primary};`);
    for (const step of [2, 3]) {
      out.push(`--color-primary-dark-${step}:${mixCss(primary, "black", 0.2)};`);
    }
    for (const step of [4, 5, 6, 7]) {
      out.push(`--color-primary-dark-${step}:${mixCss(primary, "black", 0.35)};`);
    }
    const lightRatios = [0.17, 0.3, 0.45, 0.58, 0.72, 0.85, 0.93];
    lightRatios.forEach((ratio, index) => {
      out.push(`--color-primary-light-${index + 1}:${mixCss(primary, "white", ratio)};`);
    });
  } else {
    out.push("--color-primary-contrast:#000000;");
    const darkRatios = [0.15, 0.15, 0.3, 0.3, 0.45, 0.45, 0.58];
    darkRatios.forEach((ratio, index) => {
      out.push(`--color-primary-dark-${index + 1}:${mixCss(primary, "white", ratio)};`);
    });
    const lightRatios = [0.12, 0.25, 0.38, 0.48, 0.48, 0.58, 0.58];
    lightRatios.forEach((ratio, index) => {
      out.push(`--color-primary-light-${index + 1}:${mixCss(primary, "black", ratio)};`);
    });
  }

  for (let step = 10; step <= 90; step += 10) {
    out.push(`--color-primary-alpha-${step}:${alphaCss(primary, step / 100)};`);
  }
  return out;
}
