/**
 * Forgejo target.
 *
 * Forgejo ships a stock theme built on ~230 `--color-*` custom properties at `:root`, plus named neutral scales (`--zinc-*` light, `--steel-*` dark). There is no supported theme file format, so the approach is to append an override fragment to the stock stylesheet at build time.
 *
 * The central design rule is **override only what differs**: anything not named here keeps Forgejo's own value, so the theme keeps tracking upstream upgrades instead of freezing a 230-variable copy that rots with every release.
 *
 * What gets emitted: the roles Forgejo names directly (`--color-body`, `--color-primary`, borders, selection…), the full neutral scales Forgejo expects ({@link ZINC_RAMP}, {@link STEEL_RAMP}; the spec only defines `surface`/`text`), and Forgejo's derived primary ramp ({@link primaryScale}).
 */

import { CSS_BANNER } from "./banner.ts";
import { alphaCss, mixCss, round } from "./color.ts";
import { assertAccessible } from "./derive.ts";
import type { Palette, PaletteMode, Scheme } from "./palette.ts";

/**
 * Forgejo's light neutral scale, `--zinc-50` … `--zinc-900`.
 *
 * Forgejo assumes a full 18-step neutral ramp; the spec only provides {@link PaletteMode.surface} and {@link PaletteMode.text}. Rather than invent eighteen colors, each step is a mix from `surface` towards `text` at the lightness ratio listed here, so the whole scale moves when the palette moves.
 *
 * The ratios are hand-tuned to match the lightness spacing of Forgejo's stock zinc scale, not generated by a formula — hence the explicit table. Step 50 is the closest to `surface`, 900 the closest to `text`.
 *
 * These same surfaces are what `gen/derive.ts` checks the muted color against, so if a ratio changes here, the matching entry in `textSurfaces` must change too.
 */
const ZINC_RAMP = [
  ["50", 0.03],
  ["100", 0.06],
  ["150", 0.09],
  ["200", 0.12],
  ["250", 0.15],
  ["300", 0.21],
  ["350", 0.32],
  ["400", 0.42],
  ["450", 0.5],
  ["500", 0.57],
  ["550", 0.64],
  ["600", 0.7],
  ["650", 0.75],
  ["700", 0.8],
  ["750", 0.85],
  ["800", 0.9],
  ["850", 0.94],
  ["900", 0.98],
] as const satisfies ReadonlyArray<readonly [string, number]>;

/**
 * Forgejo's dark neutrals that sit *below* the page background: `--steel-850` and `--steel-900`.
 *
 * The dark scale needs two colors darker than `bg` (Forgejo uses them for inset/well areas), which mixing `bg` towards `text` cannot produce — it only ever gets lighter. These are therefore mixed towards literal `black`.
 */
const STEEL_DARKER = [
  ["900", 0.3],
  ["850", 0.15],
] as const satisfies ReadonlyArray<readonly [string, number]>;

/**
 * Forgejo's dark neutrals at or above the page background: `--steel-750` up to `--steel-100`.
 *
 * Same construction as {@link ZINC_RAMP} — a mix from `bg` towards `text` — with the ratios hand-tuned to Forgejo's stock spacing. `--steel-800` is the background itself and is emitted literally by {@link pushSteel} to avoid a `color-mix()` that would echo the same color back.
 */
const STEEL_RAMP = [
  ["750", 0.08],
  ["700", 0.14],
  ["650", 0.2],
  ["600", 0.27],
  ["550", 0.35],
  ["500", 0.43],
  ["450", 0.5],
  ["400", 0.57],
  ["350", 0.64],
  ["300", 0.71],
  ["250", 0.78],
  ["200", 0.84],
  ["150", 0.9],
  ["100", 0.96],
] as const satisfies ReadonlyArray<readonly [string, number]>;

/**
 * Pushes one indented `--custom-property: value;` declaration.
 *
 * Every declaration goes through here so the emitted fragment is valid and *canonically formatted* (`deno fmt`) without a post-processing step. The generated files are committed, so they are covered by `deno fmt --check`; a stray compact `--x:y;` would fail CI.
 */
function decl(out: string[], property: string, value: string): void {
  out.push(`  ${property}: ${value};`);
}

/**
 * Renders the CSS override fragment for one scheme: `forgejo/motif-light.css` or `forgejo/motif-dark.css`.
 *
 * Both fragments target bare `:root` — Forgejo loads light and dark as separate stylesheets and activates one, so the scheme is chosen by *which file is applied*, not by a selector inside the file.
 *
 * @returns A complete CSS file: banner, `:root { … }`, trailing newline.
 * @throws If {@link assertAccessible} rejects the scheme's muted color.
 */
export function renderForgejo(scheme: Scheme, palette: Palette): string {
  const mode = palette[scheme];
  const worst = assertAccessible(scheme, palette);
  const out: string[] = [CSS_BANNER, ":root {"];

  if (scheme === "light") {
    decl(out, "--color-body", mode.bg);
    out.push(mutedComment(worst));
    pushMuted(out, mode.textMuted);
    decl(out, "--color-secondary", mode.border);
    decl(out, "--color-input-border", mode.border);
    decl(out, "--color-input-border-hover", mode.borderHover);
    decl(out, "--color-timeline", mode.border);
    decl(out, "--color-hover", alphaCss(mode.surface, 0.8));
    decl(out, "--color-active", mode.border);
    decl(out, "--color-selection-bg", mode.primary);
    pushZinc(out, mode);
  } else {
    decl(out, "--color-secondary", mode.border);
    out.push(mutedComment(worst));
    pushMuted(out, mode.textMuted);
    decl(out, "--color-input-border", mode.border);
    decl(out, "--color-input-border-hover", mode.borderHover);
    decl(out, "--color-timeline", mode.border);
    decl(out, "--color-selection-bg", mode.primary);
    decl(out, "--color-selection-fg", mode.bg);
    pushSteel(out, mode);
  }

  out.push(...primaryScale(scheme, mode));
  out.push("}");
  return `${out.join("\n")}\n`;
}

/** Emits the muted-text note; indented to sit inside the `:root` block. */
function mutedComment(worst: number): string {
  return `  /* Muted text: the spec's single textMuted color, AA-verified against every text-bearing surface in this scheme (worst case ${
    round(worst)
  }:1). All four --color-text-light* slots share it, as does --color-placeholder-text. */`;
}

/**
 * Emits Forgejo's four muted-text slots from one color.
 *
 * Forgejo expects a graded scale (`--color-text-light` plus `-1`…`-3`), but the spec defines a single {@link PaletteMode.textMuted}. Rather than synthesise three near-identical extra colors, all four slots point at the one AA-checked value: a flat "muted" level that is provably accessible, over a fake gradient that is not.
 */
function pushMuted(out: string[], color: string): void {
  for (
    const name of [
      "--color-text-light",
      "--color-text-light-1",
      "--color-text-light-2",
      "--color-text-light-3",
    ]
  ) {
    decl(out, name, color);
  }
}

/** Emits the light neutral scale from {@link ZINC_RAMP}. */
function pushZinc(out: string[], mode: PaletteMode): void {
  for (const [step, ratio] of ZINC_RAMP) {
    decl(out, `--zinc-${step}`, mixCss(mode.surface, mode.text, ratio));
  }
}

/**
 * Emits the dark neutral scale: {@link STEEL_DARKER}, then `--steel-800` literally, then {@link STEEL_RAMP}.
 *
 * Ordering matches the numeric order of the scale, so the generated file reads top-to-bottom as `steel-900`, `steel-850`, `steel-800`, `steel-750` … which makes a visual review of the ramp possible.
 */
function pushSteel(out: string[], mode: PaletteMode): void {
  for (const [step, ratio] of STEEL_DARKER) {
    decl(out, `--steel-${step}`, mixCss(mode.bg, "black", ratio));
  }
  decl(out, "--steel-800", mode.bg);
  for (const [step, ratio] of STEEL_RAMP) {
    decl(out, `--steel-${step}`, mixCss(mode.bg, mode.text, ratio));
  }
}

/**
 * Emits Forgejo's derived primary steps: contrast pairs, seven `-dark-*`, seven `-light-*`, and nine `-alpha-*` opacities.
 *
 * These exist because Forgejo asks for a *ramp* per accent (button states, hover tints, focus rings) that the spec does not model — it only defines {@link PaletteMode.primary} and {@link PaletteMode.primaryOffset}. Each step is therefore a mix towards `black` or `white`.
 *
 * The two schemes are not mirror images: in light, `dark-*` shades the accent and `light-*` tints it; in dark, the roles are swapped so both ramps still move away from the surrounding surface. The ratios are hand-tuned against Forgejo's stock accent ramp, which is why they are literal tables and include deliberate repeats (two consecutive steps sharing a ratio) rather than a formula.
 */
function primaryScale(scheme: Scheme, mode: PaletteMode): string[] {
  const primary = mode.primary;
  const out: string[] = [];
  decl(out, "--color-primary", primary);

  if (scheme === "light") {
    decl(out, "--color-primary-contrast", "#ffffff");
    decl(out, "--color-primary-dark-1", primary);
    for (const step of [2, 3]) {
      decl(out, `--color-primary-dark-${step}`, mixCss(primary, "black", 0.2));
    }
    for (const step of [4, 5, 6, 7]) {
      decl(out, `--color-primary-dark-${step}`, mixCss(primary, "black", 0.35));
    }
    const lightRatios = [0.17, 0.3, 0.45, 0.58, 0.72, 0.85, 0.93];
    lightRatios.forEach((ratio, index) => {
      decl(out, `--color-primary-light-${index + 1}`, mixCss(primary, "white", ratio));
    });
  } else {
    decl(out, "--color-primary-contrast", "#000000");
    const darkRatios = [0.15, 0.15, 0.3, 0.3, 0.45, 0.45, 0.58];
    darkRatios.forEach((ratio, index) => {
      decl(out, `--color-primary-dark-${index + 1}`, mixCss(primary, "white", ratio));
    });
    const lightRatios = [0.12, 0.25, 0.38, 0.48, 0.48, 0.58, 0.58];
    lightRatios.forEach((ratio, index) => {
      decl(out, `--color-primary-light-${index + 1}`, mixCss(primary, "black", ratio));
    });
  }

  for (let step = 10; step <= 90; step += 10) {
    decl(out, `--color-primary-alpha-${step}`, alphaCss(primary, step / 100));
  }
  return out;
}
